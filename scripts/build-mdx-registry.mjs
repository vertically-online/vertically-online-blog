// Generates components/content/mdx-registry.tsx: a client component that
// renders any MDX body under content/blog or content/landing by id
// ("blog/<slug>", "landing/<slug>"). Rendering bodies through a client
// component keeps Next from embedding a second JSON copy of every article in
// the page's RSC payload (it sends a reference instead); the HTML is still
// fully server-rendered. Static imports, not next/dynamic, so SSR always has
// the content. Runs in predev/prebuild; also `npm run mdx-registry`.
import fs from "node:fs";
import path from "node:path";

const entries = [];
for (const dir of ["blog", "landing"]) {
  const folder = path.join(process.cwd(), "content", dir);
  if (!fs.existsSync(folder)) continue;
  for (const file of fs.readdirSync(folder).filter((f) => f.endsWith(".mdx")).sort()) {
    entries.push({ id: `${dir}/${file.replace(/\.mdx$/, "")}`, file: `@/content/${dir}/${file}` });
  }
}

const out = `// Generated by scripts/build-mdx-registry.mjs. Do not edit by hand.
"use client";

import type { ComponentType } from "react";
${entries.map((e, i) => `import Body${i} from "${e.file}";`).join("\n")}

const BODIES: Record<string, ComponentType> = {
${entries.map((e, i) => `  "${e.id}": Body${i},`).join("\n")}
};

export default function MdxBody({ id }: { id: string }) {
  const Body = BODIES[id];
  if (!Body) throw new Error(\`No MDX body registered for "\${id}"\`);
  return <Body />;
}
`;
fs.writeFileSync(path.join(process.cwd(), "components/content/mdx-registry.tsx"), out);
console.log(`mdx-registry: ${entries.length} bodies`);
